package com.leomaradan.mapgen.mixin;

import com.leomaradan.mapgen.world.MapChunkGenerator;
import com.mojang.serialization.Lifecycle;
import net.minecraft.core.MappedRegistry;
import net.minecraft.core.Registry;
import net.minecraft.core.RegistrationInfo;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.dimension.LevelStem;
import net.minecraft.world.level.levelgen.WorldDimensions;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyVariable;

import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;

@Mixin(WorldDimensions.class)
public abstract class WorldDimensionsMixin {

    /**
     * {@code bake} prefers the dimensions of datapacks and mods to the world's own. A dimension
     * generated by a map (a mod's dimension it replaces, or the new dimension it adds) must keep the
     * map's generator, when the world is created and every time it is loaded: drop those from the
     * datapack dimensions.
     */
    @ModifyVariable(method = "bake", at = @At("HEAD"), argsOnly = true)
    private Registry<LevelStem> mapgen$keepMapDimensions(Registry<LevelStem> baseDimensions) {
        Map<ResourceKey<LevelStem>, LevelStem> own = ((WorldDimensions) (Object) this).dimensions();
        Set<ResourceKey<LevelStem>> mapped = own.entrySet().stream()
                .filter(e -> e.getValue().generator() instanceof MapChunkGenerator generator && generator.settings().isConfigured())
                .map(Map.Entry::getKey)
                .filter(baseDimensions::containsKey)
                .collect(Collectors.toSet());
        if (mapped.isEmpty()) {
            return baseDimensions;
        }
        MappedRegistry<LevelStem> kept = new MappedRegistry<>(Registries.LEVEL_STEM, Lifecycle.stable());
        for (ResourceKey<LevelStem> key : baseDimensions.registryKeySet()) {
            if (!mapped.contains(key)) {
                kept.register(key, baseDimensions.getValueOrThrow(key), baseDimensions.registrationInfo(key).orElse(RegistrationInfo.BUILT_IN));
            }
        }
        return kept.freeze();
    }
}
